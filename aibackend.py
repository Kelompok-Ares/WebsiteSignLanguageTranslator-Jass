def build_hand_adjacency():
    A_single = np.eye(21, dtype=np.float32)
    for i, j in HAND_CONNECTIONS:
        A_single[i, j] = A_single[j, i] = 1.0
    A_single = A_single / A_single.sum(axis=1, keepdims=True)
    A = np.zeros((42, 42), dtype=np.float32)
    A[:21, :21] = A_single
    A[21:, 21:] = A_single
    return A

HAND_ADJACENCY = build_hand_adjacency()

def build_bone_adjacency():
    num_bones = len(HAND_CONNECTIONS)
    A_single = np.eye(num_bones, dtype=np.float32)
    for i in range(num_bones):
        for j in range(num_bones):
            if i != j:
                # Two bones are adjacent if they share a joint
                if bool(set(HAND_CONNECTIONS[i]) & set(HAND_CONNECTIONS[j])):
                    A_single[i, j] = 1.0
    A_single = A_single / A_single.sum(axis=1, keepdims=True)
    A = np.zeros((num_bones * 2, num_bones * 2), dtype=np.float32)
    A[:num_bones, :num_bones] = A_single
    A[num_bones:, num_bones:] = A_single
    return A

BONE_ADJACENCY = build_bone_adjacency()

