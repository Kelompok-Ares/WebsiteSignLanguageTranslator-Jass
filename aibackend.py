class DataProcessor:
    @staticmethod
    def _normalize_pair(left_raw, right_raw):
        def normalize(hand_raw):
            if hand_raw[0] == Config.MASK_VALUE:
                return np.full(63, Config.MASK_VALUE, dtype=np.float32)
            
            # Reshape to (21, 3) to compute per-hand bounding box
            pts = hand_raw.reshape(21, 3)
            # Find valid points (just in case some are masked, though usually all or none)
            valid_pts = pts[pts[:, 0] != Config.MASK_VALUE]
            if len(valid_pts) == 0:
                return np.full(63, Config.MASK_VALUE, dtype=np.float32)
                
            origin = valid_pts[0] # Use wrist as origin for this hand
            scale = max((valid_pts.max(axis=0) - valid_pts.min(axis=0)).max(), 1e-4)
            
            normalized = np.zeros(63, dtype=np.float32)
            for i in range(0, 63, 3):
                if hand_raw[i] == Config.MASK_VALUE:
                    normalized[i:i+3] = Config.MASK_VALUE
                else:
                    normalized[i]   = (hand_raw[i] - origin[0]) / scale
                    normalized[i+1] = (hand_raw[i+1] - origin[1]) / scale
                    normalized[i+2] = (hand_raw[i+2] - origin[2]) / scale
            return normalized

        left_norm = normalize(left_raw)
        right_norm = normalize(right_raw)
        hand_presence = np.array([
            left_raw[0] != Config.MASK_VALUE,
            right_raw[0] != Config.MASK_VALUE
        ], dtype=bool)

        return left_norm, right_norm, hand_presence

    @staticmethod
    def extract_features(raw_landmarks):
        if raw_landmarks is None or len(raw_landmarks) != Config.JOINT_DIM:
            return np.full(Config.FEATURE_DIM, Config.MASK_VALUE, dtype=np.float32), np.array([False, False], dtype=bool)

        raw_landmarks = np.array(raw_landmarks, dtype=np.float32)
        left_hand_raw = raw_landmarks[:63]
        right_hand_raw = raw_landmarks[63:]

        left_norm, right_norm, hand_presence = DataProcessor._normalize_pair(left_hand_raw, right_hand_raw)

        joints = np.concatenate([left_norm, right_norm])
        bones = np.full(Config.BONE_DIM, Config.MASK_VALUE, dtype=np.float32)

        def compute_bones(norm_hand, offset):
            if norm_hand[0] == Config.MASK_VALUE:
                return

            idx = 0
            for start, end in HAND_CONNECTIONS:
                start_i, end_i = start * 3, end * 3
                if start_i + 2 >= len(norm_hand) or end_i + 2 >= len(norm_hand):
                    continue

                bones[offset + idx]     = norm_hand[end_i]   - norm_hand[start_i]
                bones[offset + idx + 1] = norm_hand[end_i+1] - norm_hand[start_i+1]
                bones[offset + idx + 2] = norm_hand[end_i+2] - norm_hand[start_i+2]
                idx += 3

        compute_bones(left_norm, 0)
        compute_bones(right_norm, 63)

        result = np.concatenate([joints, bones])
        assert len(result) == Config.FEATURE_DIM, (
            f"extract_features output dim mismatch: expected {Config.FEATURE_DIM}, got {len(result)}"
        )
        return result, hand_presence

    @staticmethod
    def temporal_resampling(buffer, target_frames=Config.SEQUENCE_LENGTH):
        if len(buffer) == 0:
            return np.full((target_frames, Config.FEATURE_DIM), Config.MASK_VALUE, dtype=np.float32)

        features_list = []
        for b in buffer:
            feat = b.get('features') if isinstance(b, dict) else None
            if feat is None:
                feat = np.full(Config.FEATURE_DIM, Config.MASK_VALUE, dtype=np.float32)
            elif isinstance(feat, tuple):
                feat = feat[0]
            features_list.append(feat)
        features = np.array(features_list)
        is_valid = ~np.all(features == Config.MASK_VALUE, axis=1)

        resampled = np.full((target_frames, Config.FEATURE_DIM), Config.MASK_VALUE, dtype=np.float32)

        if not np.any(is_valid):
            return resampled

        valid_features = features[is_valid]
        num_frames = len(valid_features)

        if num_frames > target_frames:
            indices = np.round(np.linspace(0, num_frames - 1, target_frames)).astype(int)
            resampled = valid_features[indices]
        else:
            resampled[:num_frames] = valid_features

        return resampled

class Augmentation:
    @staticmethod
    def spatial_scale(sequence, scale_range=(0.8, 1.2)):
        seq = np.copy(sequence)
        scale = np.random.uniform(*scale_range)
        mask = (seq != Config.MASK_VALUE)
        seq[mask] *= scale
        return seq

    @staticmethod
    def time_warp(buffer):
        if len(buffer) < 5: return buffer
        buf_copy = list(buffer)
        warp_type = random.choice(['fast', 'slow'])
        num_frames = random.randint(2, min(5, len(buf_copy)-2))

        if warp_type == 'fast':
            max_removable = max(0, len(buf_copy) - 3)
            num_frames = min(num_frames, max_removable)
            for _ in range(num_frames):
                if len(buf_copy) <= 3:
                    break
                idx = random.randint(1, len(buf_copy)-2)
                buf_copy.pop(idx)
        else:
            for _ in range(num_frames):
                idx = random.randint(1, len(buf_copy)-2)
                buf_copy.insert(idx, buf_copy[idx].copy())
        return buf_copy


