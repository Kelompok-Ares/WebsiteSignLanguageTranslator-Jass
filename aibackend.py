class ProgressTrackingCallback(tf.keras.callbacks.Callback):
    def __init__(self, total_epochs):
        super().__init__()
        self.total_epochs = total_epochs

    def on_epoch_begin(self, epoch, logs=None):
        _training_progress['current_epoch'] = epoch + 1
        _training_progress['total_epochs'] = self.total_epochs

    def on_epoch_end(self, epoch, logs=None):
        if logs is None:
            logs = {}
        log_entry = {
            'epoch': epoch + 1,
            'loss': round(float(logs.get('loss', 0)), 4),
            'acc': round(float(logs.get('accuracy', 0)), 4),
        }
        if 'val_loss' in logs:
            log_entry['valLoss'] = round(float(logs['val_loss']), 4)
        if 'val_accuracy' in logs:
            log_entry['valAcc'] = round(float(logs['val_accuracy']), 4)
        _training_progress['logs'].append(log_entry)

