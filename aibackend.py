@tf.keras.utils.register_keras_serializable()
class ComputeFrameMask(layers.Layer):
    def call(self, inputs):
        return tf.reduce_any(tf.not_equal(inputs, Config.MASK_VALUE), axis=-1)

@tf.keras.utils.register_keras_serializable()
class CleanInputs(layers.Layer):
    def call(self, inputs):
        return tf.where(tf.not_equal(inputs, Config.MASK_VALUE), inputs, tf.zeros_like(inputs))

@tf.keras.utils.register_keras_serializable()
class SplitJoints(layers.Layer):
    def call(self, inputs):
        return inputs[:, :, :Config.JOINT_DIM]

@tf.keras.utils.register_keras_serializable()
class SplitBones(layers.Layer):
    def call(self, inputs):
        return inputs[:, :, Config.JOINT_DIM:]

@tf.keras.utils.register_keras_serializable()
class ComputeAttentionMask(layers.Layer):
    def call(self, fm):
        mask = tf.cast(fm[:, tf.newaxis, :], tf.bool) & tf.cast(fm[:, :, tf.newaxis], tf.bool)
        return mask

@tf.keras.utils.register_keras_serializable()
class MaskAwarePool(layers.Layer):
    def call(self, inputs):
        features, fm = inputs
        float_mask = tf.cast(fm, tf.float32)[:, :, tf.newaxis]
        masked_features = features * float_mask
        return tf.reduce_sum(masked_features, axis=1) / (tf.reduce_sum(float_mask, axis=1) + 1e-8)


@tf.keras.utils.register_keras_serializable()
class GraphConv(layers.Layer):
    def __init__(self, units, adjacency_matrix, **kwargs):
        super().__init__(**kwargs)
        self.units = units
        self.adjacency_matrix = tf.constant(adjacency_matrix, dtype=tf.float32)
        self.dense = layers.Dense(units, activation='relu')

    def call(self, x):
        agg = tf.einsum('ij,btjc->btic', self.adjacency_matrix, x)
        return self.dense(tf.concat([x, agg], axis=-1))

    def get_config(self):
        config = super().get_config()
        config.update({
            'units': self.units,
            'adjacency_matrix': self.adjacency_matrix.numpy().tolist()
        })
        return config

    @classmethod
    def from_config(cls, config):
        adjacency_matrix = config.pop('adjacency_matrix')
        return cls(adjacency_matrix=adjacency_matrix, **config)

def build_two_stream_model(sequence_length=Config.SEQUENCE_LENGTH, num_classes=None):
    if num_classes is None or num_classes < 2:
        raise ValueError(f"num_classes must be >= 2, got {num_classes}")
    inputs = layers.Input(shape=(sequence_length, Config.FEATURE_DIM), name="feature_input")

    frame_mask = ComputeFrameMask(name="frame_mask")(inputs)
    clean_inputs = CleanInputs(name="clean_inputs")(inputs)

    joints = SplitJoints(name="split_joints")(clean_inputs)
    bones = SplitBones(name="split_bones")(clean_inputs)

    def process_stream(x, name_prefix, adjacency_matrix, num_nodes):
        x = layers.Reshape((sequence_length, num_nodes * 2, 3), name=f"{name_prefix}_reshape")(x)
        x = GraphConv(units=32, adjacency_matrix=adjacency_matrix, name=f"{name_prefix}_graph")(x)
        x = layers.TimeDistributed(layers.Flatten(), name=f"{name_prefix}_flat")(x)
        x = layers.Bidirectional(
            layers.LSTM(128, return_sequences=True),
            name=f"{name_prefix}_bilstm"
        )(x, mask=frame_mask)
        return x

    x_joints = process_stream(joints, "joint", HAND_ADJACENCY, 21)
    x_bones = process_stream(bones, "bone", BONE_ADJACENCY, 21)

    x = layers.Concatenate(name="fusion")([x_joints, x_bones])

    attention_mask = ComputeAttentionMask(name="attention_mask")(frame_mask)

    attention_out = layers.MultiHeadAttention(
        num_heads=4, key_dim=32, name="mha"
    )(x, x, attention_mask=attention_mask)
    
    x = layers.Add(name="residual")([x, attention_out])
    x = layers.LayerNormalization(name="layer_norm")(x)

    x = MaskAwarePool(name="mask_aware_pool")([x, frame_mask])

    x = layers.Dropout(0.5)(x)
    x = layers.Dense(256, activation='relu', kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(128, activation='relu', kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)
    outputs = layers.Dense(num_classes, activation='softmax', name="classifier",
                           kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)

    model = models.Model(inputs=inputs, outputs=outputs)
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
                  loss='sparse_categorical_crossentropy', metrics=['accuracy'])
    return model


