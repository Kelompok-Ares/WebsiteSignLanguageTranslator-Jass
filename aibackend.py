async def train(request: Request, payload: TrainRequest):
    auth_header = request.headers.get('X-Train-Secret')
    if auth_header != Config.TRAIN_SECRET:
        return JSONResponse(
            {'error': 'Unauthorized: invalid or missing X-Train-Secret header'},
            status_code=401
        )

    max_epochs = min(payload.epochs, Config.MAX_EPOCHS)
    if payload.epochs != max_epochs:
        print(f"⚠️ Clamped epochs from {payload.epochs} to {max_epochs}")

    if _train_lock.locked():
        return JSONResponse(
            {'error': 'Server sedang melatih model lain. Harap tunggu hingga selesai.'},
            status_code=429
        )

    persisted_samples = load_persisted_samples()
    # Unwrap dict-wrapped features from frontend
    processed_new = []
    for s in payload.samples:
        sample = {'label': s['label']}
        raw_feats = s.get('features', [])
        unwrapped = []
        for f in raw_feats:
            if isinstance(f, dict) and 'features' in f:
                unwrapped.append(f['features'])
            else:
                unwrapped.append(f)
        sample['features'] = unwrapped
        processed_new.append(sample)
    all_samples = persisted_samples + processed_new
    print(f"📊 Training with {len(persisted_samples)} persisted + {len(payload.samples)} new = {len(all_samples)} total samples")

    _training_progress.update({
        'is_training': True,
        'current_epoch': 0,
        'total_epochs': max_epochs,
        'logs': [],
        'error': None,
        'cancel_requested': False,
    })

    async with _train_lock:
        try:
            unique_labels = set(s['label'] for s in all_samples)
            if len(unique_labels) < 2:
                _training_progress.update({'is_training': False, 'error': 'Need at least 2 labels'})
                return JSONResponse(
                    {'error': 'Minimal membutuhkan 2 kelas/label yang berbeda untuk training.'},
                    status_code=400
                )

            sign_model.is_training_active = True

            loop = asyncio.get_running_loop()
            logs = await loop.run_in_executor(None, sign_model.train, all_samples, max_epochs)

            save_samples(processed_new)

            _training_progress.update({
                'is_training': False,
                'current_epoch': max_epochs,
                'logs': logs,
            })

            return {'success': True, 'labels': sign_model.labels, 'logs': logs, 'total_epochs': len(logs)}
        except Exception as e:
            _training_progress.update({'is_training': False, 'error': str(e)})
            return JSONResponse({'error': str(e)}, status_code=500)
        finally:
            sign_model.is_training_active = False

